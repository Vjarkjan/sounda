#!/usr/bin/env python3
"""Build pixel-aligned Unifont glyphs and Unicode lookup tables off device.

Usage: python3 scripts/build_unicode.py output/unicode-font/unifont-18.0.01.hex
Font: https://unifoundry.com/pub/unifont/unifont-18.0.01/
"""
from pathlib import Path
import argparse
import hashlib
import json
import struct
import unicodedata as ud

ROOT = Path(__file__).resolve().parents[1]
RANGES = [(0x20, 0x52f), (0x1c80, 0x1c8f), (0x1d00, 0x1eff),
          (0x2000, 0x206f), (0x2c60, 0x2c7f), (0x2de0, 0x2dff),
          (0x3000, 0x31ff), (0x3400, 0x9fff), (0xa640, 0xa7ff),
          (0xab30, 0xab6f), (0xf900, 0xfaff), (0xfe00, 0xfe6f), (0xff00, 0xffef)]
EXTRA = {0x25a1, 0xfffd}
EXPAND = dict(zip('łŁßẞæÆœŒøØđĐðÐþÞı',
                  ['l','l','ss','ss','ae','ae','oe','oe','o','o','d','d','d','d','th','th','i']))


def fold(c):
    result = ''
    for part in ud.normalize('NFKC', c).casefold():
        if part in EXPAND:
            result += EXPAND[part]
        elif 'LATIN' in ud.name(part, ''):
            result += ''.join(p for p in ud.normalize('NFKD', part) if not ud.combining(p))
        elif 0x30a1 <= ord(part) <= 0x30f6:
            result += chr(ord(part) - 0x60)
        else:
            result += part
    return result


def rust_str(text):
    return '"' + ''.join('\\u{' + format(ord(c), 'x') + '}' for c in text) + '"'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('hex', type=Path)
    args = parser.parse_args()
    glyphs = {}
    for line in args.hex.read_text().splitlines():
        if not line or line.startswith('#'): continue
        point, data = line.split(':')
        cp = int(point, 16)
        if cp not in EXTRA and not any(a <= cp <= b for a, b in RANGES): continue
        raw = bytes.fromhex(data)
        if len(raw) not in (16, 32): continue
        rows = b''.join(struct.pack('<H', value << 8) for value in raw) if len(raw) == 16 else b''.join(struct.pack('<H', int.from_bytes(raw[i:i+2], 'big')) for i in range(0,32,2))
        glyphs[cp] = struct.pack('<IB3x', cp, 8 if len(raw) == 16 else 16) + rows
    atlas = b''.join(glyphs[cp] for cp in sorted(glyphs))
    (ROOT/'assets/fonts/unicode.bin').write_bytes(atlas)
    folds, pairs = [], []
    for cp in range(0x10000):
        c = chr(cp)
        value = fold(c)
        if value != c and not 0xd800 <= cp <= 0xdfff:
            folds.append((cp, value))
        decomposition = ud.decomposition(c)
        if decomposition and not decomposition.startswith('<'):
            values = [int(x,16) for x in decomposition.split()]
            if len(values) == 2 and ud.normalize('NFC', ''.join(map(chr, values))) == c:
                pairs.append((*values, cp))
    text = '// Generated by scripts/build_unicode.py; Unicode '+ud.unidata_version+'.\n'
    text += 'pub static FOLDS: &[(u32, &str)] = &[\n'
    text += ''.join(f'    (0x{cp:x}, {rust_str(value)}),\n' for cp, value in folds) + '];\n'
    text += 'pub static COMPOSE: &[(u32, u32, u32)] = &[\n'
    text += ''.join(f'    (0x{a:x}, 0x{b:x}, 0x{c:x}),\n' for a,b,c in sorted(pairs)) + '];\n'
    (ROOT/'src/unicode_data.rs').write_text(text)
    manifest = {'font':'GNU Unifont 18.0.01 subset', 'license':'SIL Open Font License 1.1',
                'source_sha256':hashlib.sha256(args.hex.read_bytes()).hexdigest(),
                'glyphs':len(glyphs), 'atlas_bytes':len(atlas), 'atlas_sha256':hashlib.sha256(atlas).hexdigest(),
                'unicode_data_version':ud.unidata_version, 'folds':len(folds), 'composition_pairs':len(pairs),
                'ranges':RANGES, 'extra':sorted(EXTRA)}
    (ROOT/'assets/fonts/manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
    print(json.dumps(manifest,indent=2))


if __name__ == '__main__': main()
